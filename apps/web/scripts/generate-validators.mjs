// Compile only at development/build time. Workers and browsers import the
// emitted functions, never Ajv's compiler or a Function constructor.
// https://ajv.js.org/standalone.html
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaPath = new URL("../../../contracts.schema.json", import.meta.url);
const target = new URL("../src/lib/generated/", import.meta.url);
const source = (await readFile(schemaPath, "utf8")).replace(/\r\n/g, "\n");
const schema = JSON.parse(source);
const definitions = Object.keys(schema.$defs).sort();
const ajv = new Ajv2020({
  strict: false,
  allErrors: false,
  validateFormats: true,
  // Share referenced validators instead of repeating the same canonical
  // definitions in every exported top-level validator.
  inlineRefs: false,
  code: { source: true, lines: true },
});
addFormats(ajv);
ajv.addSchema(schema, "canonical");
const mapping = Object.fromEntries(
  definitions.map((name) => [name, `canonical#/$defs/${name}`]),
);
const hash = createHash("sha256").update(source).digest("hex");
const header = `// Generated by scripts/generate-validators.mjs. Do not edit.\n// Canonical schema SHA-256 (LF): ${hash}\n`;
const outputs = {
  "validators.cjs": header + standaloneCode(ajv, mapping).trimEnd() + "\n",
  "validators.d.cts":
    header +
    "declare const validators: {\n" +
    definitions
      .map(
        (name) =>
          `  readonly ${JSON.stringify(name)}: (data: unknown) => boolean;`,
      )
      .join("\n") +
    "\n};\nexport = validators;\n",
};
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/generate-validators.mjs [--check]");
}
if (!check) await mkdir(target, { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  const file = new URL(name, target);
  if (check) {
    const actual = await readFile(file, "utf8").catch(() => null);
    if (actual?.replace(/\r\n/g, "\n") !== content) {
      throw new Error(
        `${fileURLToPath(file)} is stale. Run node scripts/generate-validators.mjs.`,
      );
    }
  } else {
    await writeFile(file, content);
  }
}
console.log(
  `${check ? "Verified" : "Generated"} ${definitions.length} canonical standalone validators.`,
);
